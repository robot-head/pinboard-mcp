//! Generate migration 2 by diffing the original typed models against collaboration.
#[path = "../src/models.rs"]
mod models;
use models::*;
#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let old = toasty::Db::builder()
        .models(toasty::models!(CanvasRecord, MutationRecord, Metadata))
        .build(toasty_driver_turso::Turso::in_memory())
        .await?;
    let next = toasty::Db::builder()
        .models(toasty::models!(
            CanvasRecord,
            MutationRecord,
            Metadata,
            UserRecord,
            SessionRecord,
            GrantRecord,
            InvitationRecord,
            CommentRecord,
            IdentityRecord
        ))
        .build(toasty_driver_turso::Turso::in_memory())
        .await?;
    let generated = toasty::migration::generate(
        next.driver(),
        &old.schema().db,
        &next.schema().db,
        &Default::default(),
    )
    .ok_or_else(|| anyhow::anyhow!("No schema changes"))?;
    println!(
        "-- Generated by Toasty 0.11 from collaboration models.\n{}",
        generated
            .migration
            .statements()
            .join("\n-- #[toasty::breakpoint]\n")
    );
    Ok(())
}
