//! Regenerate only the initial migration when developing a fresh, unreleased schema.
//! Once released, add versioned migrations instead of modifying migration 1.
#[path = "../src/models.rs"]
mod models;
use models::{CanvasRecord, Metadata, MutationRecord};
#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let db = toasty::Db::builder()
        .models(toasty::models!(CanvasRecord, MutationRecord, Metadata))
        .build(toasty_driver_turso::Turso::in_memory())
        .await?;
    let generated = toasty::migration::generate(
        db.driver(),
        &Default::default(),
        &db.schema().db,
        &Default::default(),
    )
    .ok_or_else(|| anyhow::anyhow!("No schema generated"))?;
    println!(
        "-- Generated by Toasty 0.11 from src/models.rs.\n{}",
        generated
            .migration
            .statements()
            .join("\n-- #[toasty::breakpoint]\n")
    );
    Ok(())
}
